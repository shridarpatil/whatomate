package mcp

func init() {
	registerArea(Area{
		Key:         "analytics",
		Title:       "Analytics and dashboard widgets",
		Description: "Dashboard totals, agent performance, Meta (WhatsApp) messaging/pricing/template/call insights, and the configurable dashboard widgets.",
	})
	widgetBody := func(required ...string) map[string]any {
		return admObj(map[string]any{
			"name":        admStr("Widget title."),
			"description": admStr("What the widget shows."),
			"data_source": admStr("Required unless display_type is shortcuts. Data the widget counts, e.g. messages, contacts, campaigns, transfers, sessions (see GET /api/widgets/data-sources)."),
			"metric":      admEnum("How values are combined.", "count", "sum", "avg"),
			"field":       admStr("Field to sum or average (for metric sum/avg)."),
			"filters": admArr(admObj(map[string]any{
				"field":    admStr("Field to filter on."),
				"operator": admEnum("Comparison.", "equals", "not_equals", "contains", "gt", "lt", "gte", "lte"),
				"value":    admStr("Value to compare with."),
			}), "Conditions rows must meet."),
			"display_type":   admEnum("How the value is shown (default number). shortcuts needs no data source.", "number", "percentage", "chart", "table", "shortcuts"),
			"chart_type":     admEnum("Chart style when display_type is chart.", "line", "bar", "pie"),
			"group_by_field": admStr("Field to group chart values by."),
			"show_change":    admBool("Show change versus the previous period."),
			"color":          admStr("Accent colour."),
			"size":           admEnum("Widget size.", "small", "medium", "large"),
			"config":         map[string]any{"type": "object", "description": "Extra display options."},
			"is_shared":      admBool("true = everyone in the organisation sees this widget."),
			"grid_x":         admInt("Column position on the dashboard grid."),
			"grid_y":         admInt("Row position on the dashboard grid."),
			"grid_w":         admInt("Width in grid columns."),
			"grid_h":         admInt("Height in grid rows."),
		}, required...)
	}
	register(
		Entry{
			Area:    "analytics",
			Method:  "GET",
			Path:    "/api/analytics/dashboard",
			Summary: "Dashboard summary for a date range: messages, contacts, chatbot sessions and campaigns sent, each with % change versus the previous period of the same length, plus recent messages.",
			Query:   admDateRange(),
			Tool:    "whatomate_dashboard_analytics",
		},
		Entry{
			Area:    "analytics",
			Method:  "GET",
			Path:    "/api/analytics/messages",
			Summary: "Message analytics (placeholder endpoint; currently returns no data).",
		},
		Entry{
			Area:    "analytics",
			Method:  "GET",
			Path:    "/api/analytics/chatbot",
			Summary: "Chatbot analytics (placeholder endpoint; currently returns no data).",
		},
		Entry{
			Area:    "analytics",
			Method:  "GET",
			Path:    "/api/analytics/agents",
			Summary: "Agent performance (chats handled, transfers, response times) for a date range. Without analytics:read you only see your own figures.",
			Query: append(admDateRange(),
				Param{Name: "group_by", Type: "string", Enum: []string{"day", "week"}, Description: "Trend grouping (default day)."},
				Param{Name: "agent_id", Type: "string", Description: "Only this agent (needs analytics:read)."},
			),
		},
		Entry{
			Area:       "analytics",
			Method:     "GET",
			Path:       "/api/analytics/agents/{id}",
			Summary:    "Detailed performance for one agent (id = user ID) over a date range.",
			Permission: "analytics:read",
			Query: append(admDateRange(),
				Param{Name: "group_by", Type: "string", Enum: []string{"day", "week"}, Description: "Trend grouping (default day)."},
			),
		},
		Entry{
			Area:       "analytics",
			Method:     "GET",
			Path:       "/api/analytics/agents/comparison",
			Summary:    "Compare all agents side by side over a date range.",
			Permission: "analytics:read",
			Query:      admDateRange(),
		},
		Entry{
			Area:       "analytics",
			Method:     "GET",
			Path:       "/api/analytics/meta",
			Summary:    "WhatsApp insights from Meta for one or all accounts: message volumes, conversation pricing, template performance or call analytics.",
			Permission: "analytics:read",
			Query: []Param{
				{Name: "analytics_type", Type: "string", Required: true, Enum: []string{"analytics", "pricing_analytics", "template_analytics", "call_analytics"}, Description: "Which insight to fetch."},
				{Name: "start", Type: "string", Required: true, Description: "Start date, ISO format YYYY-MM-DD (not in the future)."},
				{Name: "end", Type: "string", Required: true, Description: "End date, ISO format YYYY-MM-DD (after start)."},
				{Name: "granularity", Type: "string", Enum: []string{"HALF_HOUR", "DAY", "MONTH"}, Description: "Time bucket (default DAY; auto-adjusted for very short or long ranges)."},
				{Name: "account_id", Type: "string", Description: "WhatsApp account ID; omit for all accounts (see GET /api/analytics/meta/accounts)."},
				{Name: "template_ids", Type: "string", Description: "template_analytics only: JSON array of Meta template IDs, e.g. [\"123\",\"456\"]."},
			},
		},
		Entry{
			Area:       "analytics",
			Method:     "GET",
			Path:       "/api/analytics/meta/accounts",
			Summary:    "List the WhatsApp accounts that Meta insights can be fetched for.",
			Permission: "analytics:read",
		},
		Entry{
			Area:        "analytics",
			Method:      "POST",
			Path:        "/api/analytics/meta/refresh",
			Summary:     "Clear cached Meta insights so the next request fetches fresh data from Meta.",
			Permission:  "analytics:write",
			SideEffects: "Drops cached analytics; the next views call Meta again.",
		},
		Entry{
			Area:       "analytics",
			Method:     "GET",
			Path:       "/api/widgets",
			Summary:    "List the dashboard widgets you can see (your own and shared ones).",
			Permission: "analytics:read",
		},
		Entry{
			Area:        "analytics",
			Method:      "POST",
			Path:        "/api/widgets",
			Summary:     "Create a dashboard widget.",
			Permission:  "analytics:write",
			Body:        widgetBody("name"),
			SideEffects: "Adds a widget to the dashboard (to everyone's if is_shared).",
		},
		Entry{
			Area:    "analytics",
			Method:  "GET",
			Path:    "/api/widgets/data-sources",
			Summary: "List the data sources and fields a widget can use.",
		},
		Entry{
			Area:    "analytics",
			Method:  "GET",
			Path:    "/api/widgets/data",
			Summary: "Calculate the values of all your visible widgets for a date range.",
			Query:   admDateRange(),
		},
		Entry{
			Area:       "analytics",
			Method:     "GET",
			Path:       "/api/widgets/{id}",
			Summary:    "Show one widget's configuration.",
			Permission: "analytics:read",
		},
		Entry{
			Area:        "analytics",
			Method:      "PUT",
			Path:        "/api/widgets/{id}",
			Summary:     "Change a widget's configuration or position.",
			Permission:  "analytics:write",
			Body:        widgetBody(),
			SideEffects: "Changes the widget for everyone who sees it.",
		},
		Entry{
			Area:        "analytics",
			Method:      "DELETE",
			Path:        "/api/widgets/{id}",
			Summary:     "Delete a dashboard widget.",
			Permission:  "analytics:delete",
			SideEffects: "Removes the widget from the dashboard.",
		},
		Entry{
			Area:    "analytics",
			Method:  "GET",
			Path:    "/api/widgets/{id}/data",
			Summary: "Calculate one widget's value for a date range.",
			Query:   admDateRange(),
		},
		Entry{
			Area:    "analytics",
			Method:  "POST",
			Path:    "/api/widgets/layout",
			Summary: "Save the dashboard layout (position and size of each widget).",
			Body: admObj(map[string]any{
				"layout": admArr(admObj(map[string]any{
					"id":     admStr("Widget ID."),
					"grid_x": admInt("Column position."),
					"grid_y": admInt("Row position."),
					"grid_w": admInt("Width in columns."),
					"grid_h": admInt("Height in rows."),
				}, "id"), "One entry per widget to place."),
			}, "layout"),
			SideEffects: "Moves and resizes widgets on the dashboard.",
		},
	)
}
