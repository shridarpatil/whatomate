package mcp

// Area "lead_ads": Meta Lead Ads pages, form mappings and received leads.

func leadMappingBody(required ...string) map[string]any {
	return setupObj(map[string]any{
		"form_id":            setupStr("Meta lead form ID (create only; one mapping per form)."),
		"form_name":          setupStr("Form name for display."),
		"is_active":          setupBool("Mapping is active."),
		"whatsapp_account":   setupStr("WhatsApp account name to send from; empty = default outgoing number."),
		"template_id":        setupStr("Approved template to send to each new lead; null = store the lead only, send nothing."),
		"template_params":    setupFreeObj("Template body variables, e.g. {\"1\":\"{{lead.first_name}}\"}. Every template variable must be mapped."),
		"header_params":      setupFreeObj("Template header variables."),
		"button_params":      setupFreeObj("Template button URL variables by button index."),
		"header_media_id":    setupStr("Media ID for image/video/document template headers."),
		"phone_field":        setupStr("Form field holding the phone (default phone_number)."),
		"name_field":         setupStr("Form field holding the name (default full_name)."),
		"consent_field":      setupStr("Form field that must be ticked before sending; empty = not enforced."),
		"tags":               setupStrArr("Tags added to the contact."),
		"assign_user_id":     setupStr("User the contact is assigned to."),
		"assign_team_id":     setupStr("Team the contact is assigned to."),
		"send_delay_seconds": setupInt("Wait before sending the template."),
		"dedupe_hours":       setupInt("Do not resend to the same phone for this form within these hours (default 24)."),
		"skip_if_opted_out":  setupBool("Skip contacts who opted out (default true)."),
	}, required...)
}

func init() {
	registerArea(Area{
		Key:   "lead_ads",
		Title: "Meta Lead Ads",
		Description: "Connect Facebook Pages, map lead forms to a WhatsApp template, and review received leads. " +
			"Each Page needs its App Secret: the public lead webhook rejects (403) unsigned or wrongly signed calls. " +
			"New leads are queued and a background worker fetches answers, upserts the contact and sends the template at most once.",
	})
	src, mp := "/api/lead-sources", "/api/lead-mappings"
	register(
		Entry{Area: "lead_ads", Method: "GET", Path: src, Summary: "List connected Facebook Pages (tokens masked) with the webhook URL to configure in Meta.", Permission: "lead_ads:read"},
		Entry{Area: "lead_ads", Method: "POST", Path: src,
			Summary:    "Connect a Facebook Page as a lead source. The Page token is checked with Meta. Next: subscribe, then map forms.",
			Permission: "lead_ads:write",
			Body: setupObj(map[string]any{
				"name":                 setupStr("Display name."),
				"page_id":              setupStr("Facebook Page ID (each Page can be connected once)."),
				"page_access_token":    setupStr("Long-lived Page access token with leads_retrieval."),
				"app_id":               setupStr("Meta App ID."),
				"app_secret":           setupStr("Meta App Secret; required so webhook signatures can be verified."),
				"default_country_code": setupStr("Country code for phones without one (default 91)."),
				"api_version":          setupStr("Graph API version like v21.0."),
			}, "name", "page_id", "page_access_token", "app_secret"),
			SideEffects: "Calls Meta to validate the Page token."},
		Entry{Area: "lead_ads", Method: "GET", Path: src + "/{id}", Summary: "Get one lead source.", Permission: "lead_ads:read"},
		Entry{Area: "lead_ads", Method: "PUT", Path: src + "/{id}",
			Summary:    "Update a lead source. Blank page_access_token / app_secret keep the stored values (the secret cannot be cleared).",
			Permission: "lead_ads:write",
			Body: setupObj(map[string]any{
				"name":                 setupStr("Display name."),
				"page_access_token":    setupStr("New Page token; blank keeps the current one."),
				"app_id":               setupStr("Meta App ID."),
				"app_secret":           setupStr("New App Secret; blank keeps the current one."),
				"default_country_code": setupStr("Default country code."),
				"api_version":          setupStr("Graph API version like v21.0."),
				"is_active":            setupBool("Pause or resume lead intake."),
			})},
		Entry{Area: "lead_ads", Method: "DELETE", Path: src + "/{id}",
			Summary: "Disconnect a Page: unsubscribes it at Meta and deletes the source with its form mappings (received leads are kept).", Permission: "lead_ads:delete",
			SideEffects: "Calls Meta to unsubscribe the Page; deletes the source and its mappings."},
		Entry{Area: "lead_ads", Method: "POST", Path: src + "/{id}/subscribe",
			Summary: "Subscribe the Page to the leadgen webhook so new leads reach Whatomate.", Permission: "lead_ads:write",
			SideEffects: "Calls Meta to subscribe the Page."},
		Entry{Area: "lead_ads", Method: "POST", Path: src + "/{id}/test",
			Summary: "Run a checklist: token valid, leads access, number of forms, subscribed, app secret set.", Permission: "lead_ads:write",
			SideEffects: "Calls Meta Graph API (read only)."},
		Entry{Area: "lead_ads", Method: "GET", Path: src + "/{id}/forms",
			Summary: "List the Page's Meta lead forms with their questions, lead counts and the Whatomate mapping if any.", Permission: "lead_ads:read",
			SideEffects: "Calls Meta Graph API (read only)."},
		Entry{Area: "lead_ads", Method: "POST", Path: src + "/{id}/sync",
			Summary:    "Backfill past leads from Meta for one form (or all mapped forms). By default backfilled leads are only stored; send=true also queues the template.",
			Permission: "lead_ads:execute",
			Body: setupObj(map[string]any{
				"form_id": setupStr("Only this form; empty = every active mapped form."),
				"since":   setupStr("Only leads created after this RFC 3339 time."),
				"send":    setupBool("Also send the mapped template to backfilled leads (default false)."),
			}),
			SideEffects: "Reads leads from Meta; with send=true WhatsApp templates go out to those leads."},
		Entry{Area: "lead_ads", Method: "GET", Path: src + "/{id}/mappings", Summary: "List form mappings of a lead source.", Permission: "lead_ads:read"},
		Entry{Area: "lead_ads", Method: "POST", Path: src + "/{id}/mappings",
			Summary:    "Map a lead form to a WhatsApp template (or store-only when template_id is null). The template must be approved and every variable mapped.",
			Permission: "lead_ads:write", Body: leadMappingBody("form_id"),
			SideEffects: "New leads from this form will receive the template automatically."},
		Entry{Area: "lead_ads", Method: "PUT", Path: mp + "/{id}",
			Summary: "Update a form mapping. All fields are overwritten, so send the full mapping.", Permission: "lead_ads:write", Body: leadMappingBody()},
		Entry{Area: "lead_ads", Method: "DELETE", Path: mp + "/{id}", Summary: "Delete a form mapping.", Permission: "lead_ads:delete",
			SideEffects: "Deletes the mapping; new leads from that form are no longer answered."},
		Entry{Area: "lead_ads", Method: "POST", Path: mp + "/{id}/preview",
			Summary:    "Preview the template message a lead would receive, using sample data or a real lead.",
			Permission: "lead_ads:read",
			Body:       setupObj(map[string]any{"lead_id": setupStr("Optional lead ID to render with real answers.")})},

		Entry{Area: "lead_ads", Method: "GET", Path: "/api/leads",
			Summary: "List received leads with status and answers.", Permission: "lead_ads:read",
			Query: append(setupPage(20),
				Param{Name: "source_id", Type: "string", Description: "Lead source ID."},
				Param{Name: "form_id", Type: "string", Description: "Meta form ID."},
				Param{Name: "status", Type: "string", Description: "Lead status.", Enum: []string{"received", "fetched", "retry", "sending", "sent", "stored",
					"skipped_duplicate", "skipped_no_mapping", "skipped_invalid_phone", "skipped_opted_out", "skipped_no_consent", "failed"}},
				Param{Name: "phone", Type: "string", Description: "Phone number contains."},
				Param{Name: "from", Type: "string", Description: "Lead created at/after, RFC 3339 time."},
				Param{Name: "to", Type: "string", Description: "Lead created at/before, RFC 3339 time."})},
		Entry{Area: "lead_ads", Method: "GET", Path: "/api/leads/stats", Summary: "Lead counts by status, today and in total.", Permission: "lead_ads:read"},
		Entry{Area: "lead_ads", Method: "GET", Path: "/api/leads/{id}", Summary: "Get one lead with its form answers, status, attempts and last error.", Permission: "lead_ads:read"},
		Entry{Area: "lead_ads", Method: "POST", Path: "/api/leads/{id}/retry",
			Summary: "Re-queue a lead for processing (fetch answers, upsert contact, send if not already sent).", Permission: "lead_ads:execute",
			SideEffects: "May send the mapped WhatsApp template to the lead."},
		Entry{Area: "lead_ads", Method: "POST", Path: "/api/leads/{id}/send",
			Summary: "Queue an explicit (re)send of the mapped template to this lead. Refused (409) while a send is in flight.", Permission: "lead_ads:execute",
			SideEffects: "Sends a WhatsApp template message to the lead."},
		Entry{Area: "lead_ads", Method: "DELETE", Path: "/api/leads/{id}",
			Summary: "Delete a lead; purge=true also wipes its personal data.", Permission: "lead_ads:delete",
			Query:       []Param{{Name: "purge", Type: "boolean", Description: "true erases the lead's personal data instead of a soft delete."}},
			SideEffects: "Deletes the lead (purge is irreversible)."},
	)
}
