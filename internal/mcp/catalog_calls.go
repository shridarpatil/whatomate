package mcp

func init() {
	registerArea(Area{
		Key:         "calls",
		Title:       "Calls and IVR",
		Description: "WhatsApp voice calling: call history and recordings, transfers of live calls to agents, outgoing calls and call permission requests, and IVR (phone menu) flows with their audio.",
	})
	ivrBody := func(required ...string) map[string]any {
		return admObj(map[string]any{
			"whatsapp_account":  admStr("Name of the WhatsApp account (phone number) this IVR answers for. Only one call-start and one outgoing-end flow per account."),
			"name":              admStr("IVR flow name."),
			"description":       admStr("What the flow does."),
			"is_active":         admBool("true = the flow is live."),
			"is_call_start":     admBool("true = run this flow when an incoming call starts on the account."),
			"is_outgoing_end":   admBool("true = run this flow at the end of outgoing calls."),
			"menu":              map[string]any{"type": "object", "description": "The IVR menu tree as built in the IVR editor: prompts (text or audio file names from POST /api/ivr-flows/audio), key-press options and their actions (sub-menu, transfer to team, hang up, etc.)."},
			"welcome_audio_url": admStr("Audio file played when the call is answered."),
		}, required...)
	}
	register(
		// Call logs
		Entry{
			Area:       "calls",
			Method:     "GET",
			Path:       "/api/call-logs",
			Summary:    "List call history (incoming and outgoing), newest first.",
			Permission: "call_logs:read",
			Query: append(admPaging(),
				Param{Name: "status", Type: "string", Enum: []string{"ringing", "answered", "completed", "missed", "rejected", "failed", "transferring", "initiating", "accepted"}, Description: "Only calls with this status."},
				Param{Name: "direction", Type: "string", Enum: []string{"incoming", "outgoing"}, Description: "Only incoming or outgoing calls."},
				Param{Name: "account", Type: "string", Description: "WhatsApp account name."},
				Param{Name: "contact_id", Type: "string", Description: "Only calls with this contact."},
				Param{Name: "ivr_flow_id", Type: "string", Description: "Only calls that went through this IVR flow."},
				Param{Name: "phone", Type: "string", Description: "Match the caller's phone number."},
			),
		},
		Entry{
			Area:       "calls",
			Method:     "GET",
			Path:       "/api/call-logs/{id}",
			Summary:    "Show one call: who, when, duration, status, IVR path and transfers.",
			Permission: "call_logs:read",
		},
		Entry{
			Area:       "calls",
			Method:     "GET",
			Path:       "/api/call-logs/{id}/recording",
			Summary:    "Get the recording of a call (if recording was on).",
			Permission: "call_logs:read",
		},
		Entry{
			Area:        "calls",
			Method:      "POST",
			Path:        "/api/call-logs/{id}/hold",
			Summary:     "Put a live call on hold (the caller hears hold music).",
			Permission:  "call_transfers:write",
			SideEffects: "Affects a live phone call.",
		},
		Entry{
			Area:        "calls",
			Method:      "POST",
			Path:        "/api/call-logs/{id}/resume",
			Summary:     "Take a live call off hold.",
			Permission:  "call_transfers:write",
			SideEffects: "Affects a live phone call.",
		},
		// Call transfers
		Entry{
			Area:       "calls",
			Method:     "GET",
			Path:       "/api/call-transfers",
			Summary:    "List calls transferred to agents/teams, newest first.",
			Permission: "call_transfers:read",
			Query: append(admPaging(),
				Param{Name: "status", Type: "string", Enum: []string{"waiting", "connected", "completed", "abandoned", "no_answer"}, Description: "Only transfers with this status."},
			),
		},
		Entry{
			Area:       "calls",
			Method:     "GET",
			Path:       "/api/call-transfers/{id}",
			Summary:    "Show one call transfer.",
			Permission: "call_transfers:read",
		},
		Entry{
			Area:       "calls",
			Method:     "POST",
			Path:       "/api/call-transfers/{id}/connect",
			Summary:    "Pick up a waiting transferred call in the browser (needs a WebRTC offer, so this is mainly for the web app).",
			Permission: "call_transfers:write",
			Body: admObj(map[string]any{
				"sdp_offer": admStr("WebRTC SDP offer from the agent's browser."),
			}, "sdp_offer"),
			SideEffects: "Connects you to a live caller.",
		},
		Entry{
			Area:        "calls",
			Method:      "POST",
			Path:        "/api/call-transfers/{id}/hangup",
			Summary:     "Hang up a transferred call.",
			Permission:  "call_transfers:write",
			SideEffects: "Ends a live phone call.",
		},
		Entry{
			Area:       "calls",
			Method:     "POST",
			Path:       "/api/call-transfers/initiate",
			Summary:    "Transfer a live call you are on to a team, optionally to one specific agent in that team.",
			Permission: "call_transfers:write",
			Body: admObj(map[string]any{
				"call_log_id": admStr("ID of the live call."),
				"team_id":     admStr("Team to transfer to."),
				"agent_id":    admStr("Optional user ID of an agent in that team to ring directly."),
			}, "call_log_id", "team_id"),
			SideEffects: "Moves a live call to someone else.",
		},
		// Outgoing calls
		Entry{
			Area:       "calls",
			Method:     "POST",
			Path:       "/api/calls/outgoing",
			Summary:    "Start a WhatsApp voice call to a contact from the browser (needs a WebRTC offer and the contact's call permission).",
			Permission: "outgoing_calls:write",
			Body: admObj(map[string]any{
				"contact_id":       admStr("Contact to call."),
				"whatsapp_account": admStr("WhatsApp account name to call from."),
				"sdp_offer":        admStr("WebRTC SDP offer from the agent's browser."),
			}, "contact_id", "whatsapp_account", "sdp_offer"),
			SideEffects: "Rings the contact's phone.",
		},
		Entry{
			Area:        "calls",
			Method:      "POST",
			Path:        "/api/calls/outgoing/{id}/hangup",
			Summary:     "Hang up an outgoing call (id = call log ID).",
			Permission:  "outgoing_calls:write",
			SideEffects: "Ends a live phone call.",
		},
		Entry{
			Area:       "calls",
			Method:     "POST",
			Path:       "/api/calls/permission-request",
			Summary:    "Ask a contact on WhatsApp for permission to call them.",
			Permission: "outgoing_calls:write",
			Body: admObj(map[string]any{
				"contact_id":       admStr("Contact to ask."),
				"whatsapp_account": admStr("WhatsApp account name to send from."),
			}, "contact_id", "whatsapp_account"),
			SideEffects: "Sends a WhatsApp call-permission message to the contact.",
		},
		Entry{
			Area:       "calls",
			Method:     "GET",
			Path:       "/api/calls/permission/{contactId}",
			Summary:    "Check whether a contact has allowed you to call them.",
			Permission: "outgoing_calls:read",
			Query: []Param{
				{Name: "whatsapp_account", Type: "string", Description: "WhatsApp account name to check for."},
			},
		},
		Entry{
			Area:    "calls",
			Method:  "GET",
			Path:    "/api/calls/ice-servers",
			Summary: "Get the STUN/TURN servers the browser uses for calls (technical, used by the web app).",
		},
		// IVR flows
		Entry{
			Area:       "calls",
			Method:     "GET",
			Path:       "/api/ivr-flows",
			Summary:    "List IVR (phone menu) flows.",
			Permission: "ivr_flows:read",
			Query: append(admPaging(),
				Param{Name: "account", Type: "string", Description: "Only flows for this WhatsApp account name."},
			),
		},
		Entry{
			Area:       "calls",
			Method:     "GET",
			Path:       "/api/ivr-flows/{id}",
			Summary:    "Show one IVR flow with its full menu.",
			Permission: "ivr_flows:read",
		},
		Entry{
			Area:        "calls",
			Method:      "POST",
			Path:        "/api/ivr-flows",
			Summary:     "Create an IVR flow.",
			Permission:  "ivr_flows:write",
			Body:        ivrBody("whatsapp_account", "name"),
			SideEffects: "When active and set as call start, incoming calls on the account follow this menu.",
		},
		Entry{
			Area:        "calls",
			Method:      "PUT",
			Path:        "/api/ivr-flows/{id}",
			Summary:     "Change an IVR flow.",
			Permission:  "ivr_flows:write",
			Body:        ivrBody(),
			SideEffects: "Changes what callers hear and can do, immediately.",
		},
		Entry{
			Area:        "calls",
			Method:      "DELETE",
			Path:        "/api/ivr-flows/{id}",
			Summary:     "Delete an IVR flow.",
			Permission:  "ivr_flows:delete",
			SideEffects: "Callers no longer get this menu.",
		},
		Entry{
			Area:        "calls",
			Method:      "POST",
			Path:        "/api/ivr-flows/audio",
			Summary:     "Upload an audio prompt for IVR menus (max 5 MB; ogg, opus, mp3, aac, m4a, wav, webm, flac). Returns the stored file name.",
			Permission:  "ivr_flows:write",
			Multipart:   &MultipartSpec{FileField: "file", Accept: "audio/*"},
			SideEffects: "Stores an audio file.",
		},
		Entry{
			Area:       "calls",
			Method:     "GET",
			Path:       "/api/ivr-flows/audio/{filename}",
			Summary:    "Download an uploaded IVR audio file.",
			Permission: "ivr_flows:read",
		},
	)
}
